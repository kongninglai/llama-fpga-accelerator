#include "dotprod.h"
#include <string.h>

static float fp16_to_fp32(uint16_t h) {
    const uint32_t sign = uint32_t(h & 0x8000u) << 16;
    const uint32_t exp = (h >> 10) & 31u;
    uint32_t mant = h & 1023u;
    uint32_t bits;
    if (exp == 0) {
        if (mant == 0) {
            bits = sign;
        } else {
            int e = -14;
            // Bounded normalization also preserves half subnormals.
            for (int k = 0; k < 10; ++k) {
                if ((mant & 1024u) == 0) { mant <<= 1; --e; }
            }
            bits = sign | (uint32_t(e + 127) << 23) | ((mant & 1023u) << 13);
        }
    } else if (exp == 31) {
        bits = sign | 0x7f800000u | (mant << 13);
    } else {
        bits = sign | ((exp + 112u) << 23) | (mant << 13);
    }
    float f;
    memcpy(&f, &bits, sizeof(f));
    return f;
}

static uint32_t byte_at(const uint32_t mem[DOTPROD_INPUT_WORDS], uint32_t i) {
#pragma HLS INLINE
    return (mem[i >> 2] >> (8 * (i & 3))) & 255u;
}

extern "C" void dotprod_accel(uint32_t n,
                              uint32_t x[DOTPROD_INPUT_WORDS],
                              uint32_t y[DOTPROD_INPUT_WORDS],
                              float *result, uint32_t *status) {
#pragma HLS INTERFACE s_axilite port=return bundle=CTRL
#pragma HLS INTERFACE s_axilite port=n bundle=CTRL offset=0x20
#pragma HLS INTERFACE s_axilite port=result bundle=CTRL offset=0x30
#pragma HLS INTERFACE s_axilite port=status bundle=CTRL offset=0x40
#pragma HLS INTERFACE s_axilite port=x bundle=CTRL offset=0x10000
#pragma HLS INTERFACE s_axilite port=y bundle=CTRL offset=0x20000

    // ap_ctrl_hs (generated by port=return) supplies start/idle/done/IRQ.
    // status is a completion payload, not a live busy register.
    if (n == 0 || n > DOTPROD_MAX_ELEMS || (n % 32) != 0) {
        *result = 0.0f;
        *status = DOTPROD_DONE | DOTPROD_ERROR;
        return;
    }

    // Preserve the original HLS eight-lane accumulation order.
    float acc[8];
#pragma HLS ARRAY_PARTITION variable=acc complete dim=1
    for (int k = 0; k < 8; ++k) acc[k] = 0.0f;
    const uint32_t blocks = n / 32;
    for (uint32_t b = 0; b < blocks; ++b) {
#pragma HLS LOOP_TRIPCOUNT min=1 max=1024
        const uint32_t base = b * 34;
        const uint16_t dx = byte_at(x, base) | (byte_at(x, base + 1) << 8);
        const uint16_t dy = byte_at(y, base) | (byte_at(y, base + 1) << 8);
        int32_t dot = 0;
        for (uint32_t j = 0; j < 32; ++j) {
#pragma HLS PIPELINE II=1
            const int xv = byte_at(x, base + 2 + j);
            const int yv = byte_at(y, base + 2 + j);
            dot += (xv < 128 ? xv : xv - 256) * (yv < 128 ? yv : yv - 256);
        }
        const float t = acc[7] + float(dot) * (fp16_to_fp32(dx) * fp16_to_fp32(dy));
        for (int k = 7; k > 0; --k) {
#pragma HLS UNROLL
            acc[k] = acc[k - 1];
        }
        acc[0] = t;
    }
    float sum = 0.0f;
    for (int k = 0; k < 8; ++k) sum += acc[k];
    *result = sum;
    *status = DOTPROD_DONE;
}
